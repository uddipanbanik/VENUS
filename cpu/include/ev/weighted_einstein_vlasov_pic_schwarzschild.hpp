/// Relativistic shell moments deposited by the Einstein-Vlasov PIC markers.
// These shell-extensive sums carry invariant particle weights before conversion
// to physical local densities. Tangential pressure is the sum of both tangential
// components. The field solve applies the radial metric volume factor.
struct WeightedEinsteinVlasovPICDepositedMoments {
    std::vector<double> shell_rest_mass;
    std::vector<double> shell_energy;
    std::vector<double> shell_radial_pressure;
    std::vector<double> shell_tangential_pressure;
    std::vector<double> shell_current;
    std::vector<double> effective_marker_number;
    double active_rest_mass = 0.0;
    double deposited_rest_mass = 0.0;
    double active_canonical_energy = 0.0;
    double deposited_canonical_energy = 0.0;
    double escaped_rest_mass = 0.0;
    double rest_mass_roundoff = 0.0;
    double canonical_energy_roundoff = 0.0;
};

