// The sampler first integrates f with coordinate dr dw deta weights. Iterate
// the source metric and multiply each fixed coordinate weight by exp(lambda)
// until the invariant polar-slice rest weights are self-consistent.
inline void canonicalize_weighted_einstein_vlasov_pic_initial_weights(
    std::vector<WeightedPICMarker>& markers,
    const Params& p) {
    std::vector<double> coordinate_weight;
    coordinate_weight.reserve(markers.size());
    for (const WeightedPICMarker& marker : markers) {
        coordinate_weight.push_back(marker.mass);
    }
    const WeightedPICFieldGrid grid =
        make_weighted_einstein_vlasov_pic_field_grid(p, p.Nr);
    bool converged = false;
    for (int iteration = 0; iteration < 32; ++iteration) {
        const WeightedEinsteinVlasovPICField field =
            deposit_and_solve_weighted_einstein_vlasov_pic_field(
                markers,
                grid,
                WeightedPICParticleShape::tsc,
                1);
        double maximum_relative_change = 0.0;
        for (std::size_t q = 0; q < markers.size(); ++q) {
            const double lambda =
                weighted_einstein_vlasov_pic_detail::
                    sample_metric_on_grid(
                        markers[q].r,
                        grid,
                        field.metric).lambda;
            const double canonical_weight =
                coordinate_weight[q] * std::exp(lambda);
            maximum_relative_change = std::max(
                maximum_relative_change,
                std::abs(canonical_weight - markers[q].mass)
                    / std::max(canonical_weight, 1.0e-300));
            markers[q].mass = canonical_weight;
        }
        if (maximum_relative_change < 2.0e-12) {
            converged = true;
            break;
        }
    }
    if (!converged) {
        throw std::runtime_error(
            "Einstein-Vlasov WPIC initial canonical weights did not converge.");
    }
}

/// Reuses the VP sampler for the coordinate measure 8*pi^2 dr dw d(eta).
/// The sampled coordinate weights
/// are subsequently multiplied by e^lambda to become invariant canonical
/// marker weights.
inline WeightedPICInitializationResult initialize_weighted_einstein_vlasov_pic(
    const std::vector<double>& f,
    const PhaseSpaceCellGeometry& geometry,
    const Params& p,
    const WeightedPICInitializationOptions& options,
    WeightedPICSamplerState& sampler) {
    validate_weighted_einstein_vlasov_pic_parameters(
        p, "Einstein-Vlasov WPIC initialization");
    Params sampler_parameters = p;
    sampler_parameters.physics_model = "vlasov_poisson";
    WeightedPICInitializationResult result = initialize_weighted_vlasov_pic(
        f, geometry, sampler_parameters, options, sampler);
    canonicalize_weighted_einstein_vlasov_pic_initial_weights(
        result.markers, p);
    result.diagnostics.represented_mass =
        weighted_pic_total_marker_mass(result.markers);
    return result;
}

