#pragma once

// Collisionless weighted particle-in-cell Einstein-Vlasov module for a
// dynamical, spherically symmetric spacetime in Schwarzschild/polar-areal
// coordinates.  This is the horizon-exterior formulation; the independent
// ingoing advanced-null module lives in
// weighted_einstein_vlasov_pic_eddington_finkelstein.hpp.
// "Static" below refers only to the non-expanding cosmological background;
// the lapse, radial metric, matter, and their coupled time evolution are
// fully dynamical.
//
// Marker conventions match weighted_vlasov_pic.hpp:
//   mass = invariant canonical phase-space/rest-number weight,
//   w    = orthonormal radial momentum,
//   eta  = L^2/2, with L the conserved angular-momentum magnitude.
//
// The module deliberately contains no collision or cosmological-expansion
// operator.  One self-consistent step performs
//
//   old deposition/constraints
//       -> half-step particle predictor
//       -> midpoint deposition/constraints
//       -> full particle push in the midpoint metric
//       -> endpoint deposition/constraints.
//
// Thus every field used by the particle pusher is generated by the same
// particles, including rho, radial pressure, radial current, lambda_t, and
// the relativistic lapse.  The finite-volume mass constraint is integrated
// directly from shell-extensive PIC energy rather than by differentiating a
// noisy density profile.  Since w is an orthonormal (not canonical) radial
// momentum, the invariant phase volume is e^lambda dr dw d(eta).  Every
// deposited stress-energy source consequently carries e^-lambda.  The radial
// constraint below solves that factor and the enclosed mass together, avoiding
// the spurious ADM-energy growth caused by treating dr dw d(eta) as invariant.

#include "ev/metric.hpp"
#include "ev/weighted_vlasov_pic.hpp"

