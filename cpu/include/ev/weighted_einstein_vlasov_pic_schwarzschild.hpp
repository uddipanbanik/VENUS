class WeightedEinsteinVlasovPICVacuumOuterBoundary : public std::runtime_error {
public:
    WeightedEinsteinVlasovPICVacuumOuterBoundary()
        : std::runtime_error(
            "Schwarzschild Einstein-Vlasov vacuum outer boundary was crossed "
            "by positive-rest-weight matter; enlarge the domain or supply "
            "an exterior matter and lapse model.") {}
};

inline void check_weighted_einstein_vlasov_pic_vacuum_outer_boundary(
    const std::vector<WeightedPICMarker>& markers) {
    for (const auto& marker : markers) {
        if (marker.state == WeightedPICMarkerState::escaped && marker.mass > 0.0) {
            throw WeightedEinsteinVlasovPICVacuumOuterBoundary();
        }
    }
}

