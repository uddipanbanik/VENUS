inline void validate_weighted_einstein_vlasov_pic_parameters(
    const Params& p,
    const char* context) {
    if (p.physics_model != "einstein_vlasov"
        || p.vp_universe != "static"
        || p.bp_collision_operator != "none"
        || !(p.inner_boundary == "reflecting"
             || p.inner_boundary == "origin_parity")
        || p.outer_boundary != "outflow_vacuum"
        || !using_cell_average_eta_grid(p)
        || !(p.metric_floor > 0.0)
        || !(p.gap_stop > 0.0)) {
        throw std::runtime_error(
            std::string(context)
            + " requires physics_model=einstein_vlasov, vp_universe=static, "
              "kinetic_grid=cell_average_eta, no collision operator, "
              "reflecting or origin_parity inner boundary, "
              "outer_boundary=outflow_vacuum, and positive "
              "metric_floor/gap_stop.");
    }
}

/// Builds a conservative radial field mesh.  Metric nodes are centered in
/// q=r^3/3, the same coordinate in which CIC/TSC marker clouds are deposited.
inline WeightedPICFieldGrid make_weighted_einstein_vlasov_pic_field_grid(
    const Params& source_parameters,
    int radial_cells) {
    validate_weighted_einstein_vlasov_pic_parameters(
        source_parameters, "Einstein-Vlasov WPIC field grid");
    if (using_origin_parity_inner(source_parameters)) {
        if (source_parameters.radial_grid != "linear") {
            throw std::runtime_error(
                "Einstein-Vlasov WPIC origin_parity requires a linear "
                "origin-resolving radial mesh.");
        }
        WeightedPICFieldGrid result;
        result.parameters = source_parameters;
        result.parameters.Nr = radial_cells;
        result.mesh.edge.resize(
            static_cast<std::size_t>(radial_cells + 1), 0.0);
        result.mesh.volume_coordinate_center.resize(
            static_cast<std::size_t>(radial_cells), 0.0);
        result.mesh.shell_volume.resize(
            static_cast<std::size_t>(radial_cells), 0.0);
        result.mesh.venus_center.resize(
            static_cast<std::size_t>(radial_cells), 0.0);
        result.mesh.venus_width.resize(
            static_cast<std::size_t>(radial_cells), 0.0);
        for (int q = 0; q <= radial_cells; ++q) {
            result.mesh.edge[static_cast<std::size_t>(q)] =
                source_parameters.r_max
                * static_cast<double>(q)
                / static_cast<double>(radial_cells);
        }
        for (int i = 0; i < radial_cells; ++i) {
            const std::size_t cell = static_cast<std::size_t>(i);
            const double left = result.mesh.edge[cell];
            const double right = result.mesh.edge[cell + 1];
            const double q0 =
                left * left * left / 3.0;
            const double q1 =
                right * right * right / 3.0;
            result.mesh.volume_coordinate_center[cell] = 0.5 * (q0 + q1);
            result.mesh.shell_volume[cell] = 4.0 * PI * (q1 - q0);
            result.mesh.venus_center[cell] = 0.5 * (left + right);
            result.mesh.venus_width[cell] = right - left;
        }
        result.radius.resize(
            result.mesh.volume_coordinate_center.size(), 0.0);
        for (std::size_t i = 0; i < result.radius.size(); ++i) {
            result.radius[i] = std::cbrt(
                3.0 * result.mesh.volume_coordinate_center[i]);
        }
        result.mesh.venus_center = result.radius;
        result.radial_coordinate =
            radial_coordinate_grid(result.radius, result.parameters);
        return result;
    }

    Params weak_field_parameters = source_parameters;
    weak_field_parameters.physics_model = "vlasov_poisson";
    WeightedPICFieldGrid result =
        make_weighted_pic_field_grid(weak_field_parameters, radial_cells);
    result.parameters = source_parameters;
    result.parameters.Nr = radial_cells;
    result.radius.resize(result.mesh.volume_coordinate_center.size(), 0.0);
    for (std::size_t i = 0; i < result.radius.size(); ++i) {
        result.radius[i] = std::cbrt(
            3.0 * result.mesh.volume_coordinate_center[i]);
    }
    result.mesh.venus_center = result.radius;
    result.radial_coordinate =
        radial_coordinate_grid(result.radius, result.parameters);
    return result;
}

